import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
const root=process.argv[2] ? path.resolve(process.argv[2]) : path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../fixtures/grok');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const events=name=>read(name+'.jsonl').trim().split('\n').map(JSON.parse);
const meta=name=>JSON.parse(read(name+'.meta.json'));
const text=es=>es.filter(e=>e.type==='text').map(e=>e.data).join('');
const end=es=>es.filter(e=>e.type==='end').at(-1);
for(const entry of JSON.parse(read('index.json')).files)assert.equal(createHash('sha256').update(read(entry.file)).digest('hex'),entry.sha256);
const seed=events('01-seed'),resume=events('02-resume');
const nonce=text(seed).match(/grok_memory_[a-f0-9]+/)?.[0];
assert.ok(nonce);assert.ok(text(resume).includes(nonce));assert.equal(end(seed).sessionId,end(resume).sessionId);
assert.equal(end(seed).stopReason,'end_turn');assert.equal(meta('01-seed').exit.code,0);
assert.equal(resume.filter(e=>e.type==='tool_call').length,0);
const denied=events('03-deny').filter(e=>e.type==='tool_call_update'&&e.status==='failed'&&JSON.stringify(e.content).includes('Denied by permission policy'));
assert.equal(denied.length,2);assert.equal(meta('03-deny').checks.editAbsent,true);assert.equal(meta('03-deny').checks.shellAbsent,true);
assert.equal(meta('03-deny').checks.positiveRead,true);assert.equal(end(events('03-deny')).stopReason,'end_turn');
assert.equal(meta('04-allow').checks.exactContent,true);
assert.ok(events('05-cancel').some(e=>e.type==='tool_call'&&e.toolName==='run_terminal_command'));
assert.equal(events('05-cancel').some(e=>e.type==='end'),false);
assert.equal(meta('05-cancel').checks.canceledWhileRunning,true);assert.equal(meta('05-cancel').checks.completionAbsent,true);assert.equal(meta('05-cancel').survivors.length,0);
assert.equal(meta('06-cancel-resume').checks.recalledNonce,true);assert.equal(meta('06-cancel-resume').checks.noTools,true);
const limited=events('07-turn-limit');assert.ok(limited.some(e=>e.type==='max_turns_reached'));assert.equal(end(limited).stopReason,'cancelled');assert.equal(meta('07-turn-limit').exit.code,1);assert.ok(text(limited).length>0);
console.log('Grok real-fixture assertions passed (7 cases, no model calls).');
